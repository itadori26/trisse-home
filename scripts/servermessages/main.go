// Command servermessages extracts every user-facing backend error message
// (kernel.NewPublicError, NewValidationError and their f variants) and
// writes the English catalogue for the frontend, keyed by
// kernel.MessageKey. A message that is not a string literal is an error:
// it could not be translated (#102).
//
// The catalogue is split by owner so that a module's messages never share a
// file with another module's (#193): a message used by exactly one module
// belongs to that module, every other message to "shared".
//
//	go run ./scripts/servermessages -out web/src/shared/api-client/generated/server-messages
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"trisse-home/internal/shared/kernel"
)

var constructors = map[string]bool{"NewPublicError": true, "NewValidationError": true, "NewPublicErrorf": true, "NewValidationErrorf": true}

// literal returns the value of a string literal or a "+" chain of literals.
func literal(e ast.Expr) (string, bool) {
	switch v := e.(type) {
	case *ast.BasicLit:
		if v.Kind != token.STRING {
			return "", false
		}
		s, err := strconv.Unquote(v.Value)
		return s, err == nil
	case *ast.BinaryExpr:
		if v.Op != token.ADD {
			return "", false
		}
		l, ok1 := literal(v.X)
		r, ok2 := literal(v.Y)
		return l + r, ok1 && ok2
	case *ast.ParenExpr:
		return literal(v.X)
	}
	return "", false
}

// ownerOf names the module a source file belongs to ("shared" outside modules).
func ownerOf(path string) string {
	parts := strings.Split(filepath.ToSlash(path), "/")
	for i := 0; i+2 < len(parts); i++ {
		if parts[i] == "internal" && parts[i+1] == "modules" {
			return parts[i+2]
		}
	}
	return "shared"
}

// collect parses the Go files below roots and returns the message templates
// and, per message key, the modules that use it.
func collect(roots []string) (map[string]string, map[string]map[string]bool, []string, error) {
	messages := map[string]string{}
	users := map[string]map[string]bool{}
	var problems []string
	fset := token.NewFileSet()
	for _, root := range roots {
		err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			f, err := parser.ParseFile(fset, path, nil, 0)
			if err != nil {
				return err
			}
			ast.Inspect(f, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok || len(call.Args) < 2 {
					return true
				}
				// kernel.NewX(...) everywhere, NewX(...) inside the kernel itself (#191).
				var name string
				switch fn := call.Fun.(type) {
				case *ast.SelectorExpr:
					if pkg, ok := fn.X.(*ast.Ident); ok && pkg.Name == "kernel" {
						name = fn.Sel.Name
					}
				case *ast.Ident:
					if f.Name.Name == "kernel" {
						name = fn.Name
					}
				}
				if !constructors[name] {
					return true
				}
				msg, ok := literal(call.Args[1])
				if !ok {
					problems = append(problems, fmt.Sprintf("%s: message is not a string literal (use kernel.%sf with {placeholders})",
						fset.Position(call.Pos()), strings.TrimSuffix(name, "f")))
					return true
				}
				key := kernel.MessageKey(msg)
				messages[key] = msg
				if users[key] == nil {
					users[key] = map[string]bool{}
				}
				users[key][ownerOf(path)] = true
				return true
			})
			return nil
		})
		if err != nil {
			return nil, nil, nil, err
		}
	}
	return messages, users, problems, nil
}

// split groups the messages by owner.
func split(messages map[string]string, users map[string]map[string]bool) map[string]map[string]string {
	byOwner := map[string]map[string]string{}
	for key, text := range messages {
		owner := "shared"
		if u := users[key]; len(u) == 1 {
			for o := range u {
				owner = o
			}
		}
		if byOwner[owner] == nil {
			byOwner[owner] = map[string]string{}
		}
		byOwner[owner][key] = text
	}
	return byOwner
}

func render(messages map[string]string) []byte {
	keys := make([]string, 0, len(messages))
	for k := range messages {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return messages[keys[i]] < messages[keys[j]] })
	var b strings.Builder
	b.WriteString("// Code generated by scripts/servermessages from the backend error messages. DO NOT EDIT.\n\n")
	b.WriteString("/** English backend messages by kernel.MessageKey; translations live in i18n/locales/server-de/. */\n")
	b.WriteString("export const serverMessages = {\n")
	for _, k := range keys {
		v, _ := json.Marshal(messages[k]) // a string: cannot fail
		fmt.Fprintf(&b, "  %s: %s,\n", k, v)
	}
	b.WriteString("} as const;\n\n/** Key of a backend message. */\nexport type ServerMessageKey = keyof typeof serverMessages;\n")
	return []byte(b.String())
}

func main() {
	out := flag.String("out", "web/src/shared/api-client/generated/server-messages", "output directory")
	flag.Parse()
	messages, users, problems, err := collect([]string{"internal", "cmd"})
	if err != nil {
		fmt.Fprintln(os.Stderr, "servermessages:", err)
		os.Exit(1)
	}
	if len(problems) > 0 {
		fmt.Fprintln(os.Stderr, strings.Join(problems, "\n"))
		os.Exit(1)
	}
	if err := write(*out, split(messages, users)); err != nil {
		fmt.Fprintln(os.Stderr, "servermessages:", err)
		os.Exit(1)
	}
	fmt.Printf("%d backend messages\n", len(messages))
}

// write renders one file per owner and removes files of owners that no longer
// have messages.
func write(dir string, byOwner map[string]map[string]string) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	for owner, messages := range byOwner {
		if err := os.WriteFile(filepath.Join(dir, owner+".ts"), render(messages), 0o644); err != nil { //nolint:gosec // generated source file
			return err
		}
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.ts"))
	if err != nil {
		return err
	}
	for _, f := range files {
		if _, ok := byOwner[strings.TrimSuffix(filepath.Base(f), ".ts")]; !ok {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
